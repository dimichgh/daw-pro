"""Minimal SMF reader — GROUND TRUTH for what the LilyPond file MEANS.
The .mid on Mutopia is generated by LilyPond from this very .ly, so it is an
INDEPENDENT instrument for checking the parser: a disagreement is a real finding,
not a rounding difference."""
import struct, sys, collections
d = open(sys.argv[1], "rb").read()
assert d[:4] == b"MThd", "not a MIDI file"
_, fmt, ntrk, div = struct.unpack(">IHHH", d[4:14])
print(f"format {fmt}, {ntrk} tracks, {div} ticks/quarter")
pos = 14
tracks = []
for t in range(ntrk):
    assert d[pos:pos+4] == b"MTrk", (t, d[pos:pos+4])
    ln = struct.unpack(">I", d[pos+4:pos+8])[0]
    body, pos = d[pos+8:pos+8+ln], pos+8+ln
    i, tick, run, ev = 0, 0, None, []
    while i < len(body):
        v = 0
        while True:
            b = body[i]; i += 1; v = (v << 7) | (b & 0x7F)
            if not b & 0x80: break
        tick += v
        st = body[i]
        if st < 0x80: st = run
        else: i += 1; run = st
        if st == 0xFF:
            mt = body[i]; i += 1
            n = 0
            while True:
                b = body[i]; i += 1; n = (n << 7) | (b & 0x7F)
                if not b & 0x80: break
            data = body[i:i+n]; i += n
            if mt == 0x03: ev.append((tick, "name", data.decode("latin1")))
            if mt == 0x51: ev.append((tick, "tempo", struct.unpack(">I", b"\0"+data)[0]))
        elif st in (0xF0, 0xF7):
            n = 0
            while True:
                b = body[i]; i += 1; n = (n << 7) | (b & 0x7F)
                if not b & 0x80: break
            i += n
        else:
            hi = st & 0xF0
            a = body[i]; i += 1
            b2 = body[i] if hi not in (0xC0, 0xD0) else None
            if hi not in (0xC0, 0xD0): i += 1
            if hi == 0x90 and b2: ev.append((tick, "on", a, b2))
            elif hi == 0x80 or (hi == 0x90 and not b2): ev.append((tick, "off", a))
    tracks.append(ev)
NAMES = "C C# D D# E F F# G G# A A# B".split()
def nn(p): return f"{NAMES[p%12]}{p//12-1}"
for t, ev in enumerate(tracks):
    ons = [(e[0], e[2]) for e in ev if e[1] == "on"]
    names = [e[2] for e in ev if e[1] == "name"]
    tempos = [e[2] for e in ev if e[1] == "tempo"]
    print(f"\ntrack {t}: {len(ons)} note-ons  name={names}  tempo(us/qn)={tempos}")
    if not ons: continue
    ps = [p for _, p in ons]
    print(f"   range {nn(min(ps))}..{nn(max(ps))}  (MIDI {min(ps)}..{max(ps)})")
    bar1 = sorted([(tk, p) for tk, p in ons if tk < 4*div])
    print("   BAR 1 (tick, pitch):", [(tk, nn(p)) for tk, p in bar1][:16])
    last = max(tk for tk, _ in ons)
    print(f"   last note-on tick {last} = bar {last/(4*div)+1:.2f}")
