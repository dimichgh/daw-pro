#!/usr/bin/env python3
r"""⭐⭐ THE ORACLE. `wtk1-prelude1.mid` was produced BY LILYPOND FROM THIS VERY
`.ly`, so it is an independent decoding of the same source by the reference
implementation. Round 29 found five silent parser failures by reasoning; this
compares note for note — pitch, onset, duration, per voice — and reports a match
rate instead of an opinion.

⚠ IT IS NOT A CIRCULAR CHECK ONLY IF THE .mid IS NOT REGENERATED BY US. It ships
in source/ beside the .ly and is treated as read-only evidence.

Usage: validate.py            (scores the current ly2notes.py)
       validate.py --before   (scores it with the round-30 fixes reverted, as a
                               POSITIVE CONTROL that the comparison can FAIL)
"""
import sys, os, struct, collections, importlib.util

HERE = os.path.dirname(os.path.abspath(__file__))
LY   = os.path.join(HERE, "wtk1-prelude1.ly")
MID  = os.path.join(HERE, "wtk1-prelude1.mid")
PARSER = os.path.join(HERE, "..", "..", "03-moonlight-long", "ly2notes.py")


def load(path):
    spec = importlib.util.spec_from_file_location("l2n", path)
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); return m


def midi_notes(path):
    d = open(path, "rb").read()
    _, fmt, ntrk, div = struct.unpack(">IHHH", d[4:14]); pos = 14; tracks = []
    for _ in range(ntrk):
        ln = struct.unpack(">I", d[pos + 4:pos + 8])[0]
        body = d[pos + 8:pos + 8 + ln]; pos += 8 + ln
        i = tick = 0; st = None; ev = []
        while i < len(body):
            n = 0
            while True:
                b = body[i]; i += 1; n = (n << 7) | (b & 0x7F)
                if not b & 0x80: break
            tick += n
            if body[i] & 0x80: st = body[i]; i += 1
            if st == 0xFF:
                i += 1; n = 0
                while True:
                    b = body[i]; i += 1; n = (n << 7) | (b & 0x7F)
                    if not b & 0x80: break
                i += n
            elif st in (0xF0, 0xF7):
                n = 0
                while True:
                    b = body[i]; i += 1; n = (n << 7) | (b & 0x7F)
                    if not b & 0x80: break
                i += n
            else:
                hi = st & 0xF0; a = body[i]; i += 1
                b2 = body[i] if hi not in (0xC0, 0xD0) else None
                if hi not in (0xC0, 0xD0): i += 1
                if hi == 0x90 and b2: ev.append((tick, a, 1))
                elif hi == 0x80 or (hi == 0x90 and not b2): ev.append((tick, a, 0))
        tracks.append(ev)
    out = []
    for ev in tracks:
        open_, ns = collections.defaultdict(list), []
        for tk, p, on in sorted(ev, key=lambda e: (e[0], e[2])):
            if on: open_[p].append(tk)
            elif open_[p]: ns.append((open_[p].pop(0), p, tk))
        out.append(sorted(ns))
    return div, out


def flat(ev):
    """ly2notes events -> [(whole_note_onset, midi, whole_note_duration)]
    ⚠ TOLERATES A None PITCH LIST so the --before control can produce a SCORE
    rather than a crash. A crash proves the old parser is broken; a score of
    0.00 % also proves the COMPARISON can report a failure, which is the thing
    a positive control is for."""
    return sorted((round(p, 9), n[0], round(d, 9))
                  for p, ns, d, r in ev if not r and ns for n in ns)


def score(name, ours, theirs, div, tol=1e-6):
    """theirs: [(tick_on, midi, tick_off)] -> whole notes; a match needs pitch,
    onset and duration to agree."""
    W = 4.0 * div
    ref = sorted((round(t / W, 9), p, round((o - t) / W, 9)) for t, p, o in theirs)
    used, hits, miss = [False] * len(ref), 0, []
    for on, p, dur in ours:
        j = next((k for k, r in enumerate(ref)
                  if not used[k] and r[1] == p and abs(r[0] - on) < tol), None)
        if j is None:
            miss.append(("no MIDI note", on, p, dur)); continue
        used[j] = True
        if abs(ref[j][2] - dur) > tol:
            miss.append(("duration", on, p, dur, ref[j][2])); continue
        hits += 1
    extra = [ref[k] for k, u in enumerate(used) if not u]
    pct = 100.0 * hits / max(len(ref), 1)
    print(f"  {name}: {len(ours)} parsed vs {len(ref)} in the MIDI — "
          f"{hits} exact ({pct:.2f} %), {len(miss)} disagreements, {len(extra)} MIDI notes unmatched")
    for m in miss[:6]: print("      MISS", m)
    for e in extra[:6]: print("      UNMATCHED", e)
    return hits, len(ref), miss, extra


if __name__ == "__main__":
    before = "--before" in sys.argv
    m = load(os.path.join(HERE, "ly2notes-before.py") if before else PARSER)
    src = open(LY).read()
    div, trk = midi_notes(MID)
    print(f"MIDI: {div} ticks/quarter, {len(trk)} tracks "
          f"({', '.join(str(len(t)) for t in trk)} notes)")
    parts = []
    try:
        if before:
            parts.append(("right hand (figure)", flat(m.parse(m.block(src, "right"), 3)[0])))
            parts.append(("left hand, both voices", flat(m.parse(m.block(src, "left"), 3)[0])))
        else:
            parts.append(("figure  (right)", flat(m.parse_voice(src, "right", 3)[0])))
            parts.append(("tenor   (left v0)", flat(m.parse_voice(src, "left", 3, voice=0)[0])))
            parts.append(("bass    (left v1)", flat(m.parse_voice(src, "left", 3, voice=1)[0])))
    except AssertionError as e:
        print(f"  parser REFUSED: {type(e).__name__}: {str(e)[:300]}")
        sys.exit(1)
    upper = [n for n in trk[2]] if len(trk) > 2 else []
    lower = [n for n in trk[1]] if len(trk) > 1 else []
    BAR = 4 * div
    bass, ten = [], []
    for b in sorted(set(t // BAR for t, _, _ in lower)):
        inb = [n for n in lower if n[0] // BAR == b]
        lo = min(p for _, p, _ in inb)
        for n in inb: (bass if n[1] == lo else ten).append(n)
    ref = {"figure  (right)": upper, "tenor   (left v0)": sorted(ten),
           "bass    (left v1)": sorted(bass),
           "right hand (figure)": upper, "left hand, both voices": lower}
    tot_h = tot_n = 0
    for nm, ours in parts:
        h, n, _, _ = score(nm, ours, ref[nm], div)
        tot_h += h; tot_n += n
    print(f"  TOTAL: {tot_h}/{tot_n} = {100.0*tot_h/max(tot_n,1):.2f} % exact")
    sys.exit(0 if tot_h == tot_n and tot_n else 1)
