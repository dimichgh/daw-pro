import Foundation

// Bundled sampler content (m30-a). A fresh project ships NO sample audio, so
// the built-in Sampler cannot make a sound out of the box — which means nobody
// (human or agent) can smoke-test a sampler feature without first sourcing
// audio from somewhere else. Verifying the m29 bend-range/voice-mode work took
// a five-step detour for exactly this reason: render a GM note to a wav, find
// somewhere to put it, mount it with a hand-computed root pitch, then measure.
// A caller reaching for the Sampler for the first time gets SILENCE, and
// silence looks exactly like a broken feature.
//
// So the repo ships one small, generated one-shot with a DOCUMENTED root pitch,
// and this file is the ONE place that knows its name, its facts, and where its
// bytes live. Pure Foundation — DAWCore stays UI-free and engine-free (LAW L9);
// nothing here decodes audio, it only resolves a URL.

/// One piece of bundled sample content, with everything a caller needs to mount
/// it as a `SamplerZone` and predict what it will sound like.
public struct BundledSampleInfo: Codable, Sendable, Equatable {
    /// Bare catalog name, e.g. `"test-tone-a4"`.
    public var name: String
    /// The form a caller writes in a sampler zone's `path` on the wire, e.g.
    /// `"builtin:test-tone-a4"` — the `SoundBankSource` `"gm"` sentinel idiom,
    /// one string field that is either a well-known name or a real path.
    public var wireName: String
    /// The resolved absolute path. Transparency only, and — like a sound
    /// bank's path — resolved at USE time, never a persisted identity.
    public var path: String
    /// The MIDI note at which the file plays back unshifted. A zone that mounts
    /// this file should use exactly this as its `rootPitch`.
    public var rootPitch: Int
    /// The pitch `rootPitch` sounds at, in Hz — what a render measurement
    /// should come back as.
    public var frequencyHz: Double
    public var sampleRate: Double
    public var frames: Int
    public var channels: Int
    public var durationSeconds: Double
    /// File size in bytes (the `SoundBankInfo.sizeBytes` courtesy).
    public var sizeBytes: Int
    /// One beginner-readable sentence about what it sounds like.
    public var summary: String
}

/// The bundled-sample catalog and its resolver.
///
/// ⚠️ There is deliberately NO new wire verb here. A sampler zone's `path`
/// already carries one string, and `SoundBankSource` already established this
/// repo's convention for "a well-known name OR a real path in one field" with
/// its `"gm"` sentinel. `builtin:<name>` is that seam applied to sample content,
/// so `track.setInstrument` / `instrument.setSamplerZones` mount the bundled
/// sample with no new command, no new MCP tool, and no change to any existing
/// caller (no real path has ever started with `builtin:`).
public enum BundledSamples {
    /// The prefix that marks a zone `path` as a catalog name rather than a
    /// filesystem path.
    public static let namePrefix = "builtin:"

    /// A catalog entry: the FACTS about a bundled file, independent of where
    /// the bytes turn out to live on this machine.
    public struct Entry: Sendable, Equatable {
        public let name: String
        public let fileName: String
        public let rootPitch: Int
        public let frequencyHz: Double
        public let sampleRate: Double
        public let frames: Int
        public let channels: Int
        public let summary: String

        public var wireName: String { BundledSamples.namePrefix + name }
        public var durationSeconds: Double { Double(frames) / sampleRate }
    }

    /// Everything the repo ships. Generated by `scripts/make-bundled-samples.py`
    /// — that script is the recipe, these are the numbers it produces, and the
    /// smoke test measures the rendered audio rather than trusting either.
    public static let catalog: [Entry] = [
        Entry(
            name: "test-tone-a4",
            fileName: "test-tone-a4.wav",
            // A4 = 440 Hz exactly = MIDI 69. Chosen because it is the one pitch
            // in music that needs no lookup, so a bend/transpose assertion is
            // readable without arithmetic.
            rootPitch: 69,
            frequencyHz: 440,
            sampleRate: 44_100,
            frames: 15_434,
            channels: 1,
            summary: "A 0.35 s plucked-sounding A4 (440 Hz) one-shot with two "
                + "quiet harmonics — pitched clearly enough to measure and "
                + "obvious enough to hear."),
    ]

    /// The catalog entry for a bare name or a `builtin:`-prefixed name.
    public static func entry(named raw: String) -> Entry? {
        let bare = raw.hasPrefix(namePrefix) ? String(raw.dropFirst(namePrefix.count)) : raw
        return catalog.first { $0.name == bare }
    }

    /// True for a string a caller meant as a catalog name. Deliberately keyed
    /// on the PREFIX, not on whether the name is known: `builtin:nope` is a
    /// mistake to report, never a path to fall through with.
    public static func isBundledName(_ raw: String) -> Bool {
        raw.hasPrefix(namePrefix)
    }

    /// Every known name, in catalog order — the text an error message uses to
    /// teach the caller what it could have said instead.
    public static var knownNames: [String] { catalog.map { namePrefix + $0.name } }

    /// `builtin:<name>` (or a bare `<name>`) → the absolute URL of the shipped
    /// file. Throws `ProjectError.importFailed` — the same error
    /// `SoundBankLibrary.resolve` throws for a missing bank, so a caller gets
    /// one shape of "that content is not here" from both.
    ///
    /// ⚠️ Two DIFFERENT failures, and they are worth different messages: an
    /// unknown NAME is the caller's typo, and a known name whose bytes are
    /// missing is a PACKAGING failure of ours (see `url(for:)`).
    public static func resolve(_ raw: String) throws -> URL {
        guard let entry = entry(named: raw) else {
            throw ProjectError.importFailed(
                "no bundled sample named \"\(raw)\" — known: \(knownNames.joined(separator: ", "))")
        }
        guard let url = url(for: entry) else {
            throw ProjectError.importFailed(
                "bundled sample \"\(entry.wireName)\" is missing from this build "
                    + "(expected \(entry.fileName) in the DAWCore resource bundle)")
        }
        return url
    }

    /// Resolved info for every catalog entry whose bytes are actually present.
    public static func available() -> [BundledSampleInfo] {
        catalog.compactMap { entry in
            guard let url = url(for: entry) else { return nil }
            let size = (try? FileManager.default.attributesOfItem(atPath: url.path))
                .flatMap { ($0[.size] as? NSNumber)?.intValue } ?? 0
            return BundledSampleInfo(
                name: entry.name, wireName: entry.wireName, path: url.path,
                rootPitch: entry.rootPitch, frequencyHz: entry.frequencyHz,
                sampleRate: entry.sampleRate, frames: entry.frames,
                channels: entry.channels, durationSeconds: entry.durationSeconds,
                sizeBytes: size, summary: entry.summary)
        }
    }

    // MARK: - Resource resolution

    /// Anchors `Bundle(for:)` to the image DAWCore was linked into. A plain
    /// empty class, never instantiated.
    private final class BundleAnchor {}

    /// Where the shipped bytes live, or nil if they did not make it into this
    /// build.
    ///
    /// ⚠️⚠️ DELIBERATELY NOT `Bundle.module`, and this is not a style choice.
    /// SwiftPM's generated accessor ends in `Swift.fatalError`, so a packaged
    /// app missing this resource would CRASH instead of reporting it, and its
    /// first candidate is the .app's ROOT, which `scripts/bundle.sh` refuses to
    /// put resource bundles in (a stray top-level item breaks the codesign
    /// seal). This is the `SwiftF0PitchTracker.weightsURL` /
    /// `OnboardingHeroArt.load` precedent, candidate for candidate.
    ///
    /// ⚠️ The anchor is `Bundle(for:)`, NOT `Bundle.main`: under this repo's
    /// `./scripts/test.sh` (which passes `--disable-xctest`) the running
    /// process' `Bundle.main` is SwiftPM's `swiftpm-testing-helper` inside the
    /// toolchain, so a `Bundle.main`-anchored search looks in Xcode and finds
    /// nothing.
    ///
    /// ⚠️ KNOWN GAP, the same one `SwiftF0PitchTracker.weightsURL` documents as
    /// m23-ap-2a-1: `scripts/bundle.sh` copies ONLY `daw-pro_DAWApp.bundle`
    /// into `Contents/Resources`, so `daw-pro_DAWCore.bundle` is NOT in the
    /// packaged .app today and candidate (1) misses there. Changing the ship
    /// pipeline needs the user's word (m23-dp), so this returns nil in the
    /// packaged app and `resolve` reports it in words — loud, not silent.
    public static func url(for entry: Entry) -> URL? {
        let bundleName = "daw-pro_DAWCore.bundle"
        let code = Bundle(for: BundleAnchor.self)
        var candidates: [URL?] = [
            // (1) Packaged .app: Contents/Resources/daw-pro_DAWCore.bundle —
            //     where scripts/bundle.sh puts resource bundles. See the gap
            //     note above: it does not put THIS one there yet.
            code.resourceURL?.appendingPathComponent(bundleName),
            // (2) Bare SwiftPM executable (`swift run DAWApp`): the resource
            //     bundle is emitted beside the binary.
            code.bundleURL.appendingPathComponent(bundleName),
        ]
        // (3) SwiftPM test runner ONLY: the resource bundle is the .xctest's
        //     SIBLING, not inside it. Gated on the `.xctest` extension
        //     deliberately — an unconditional "look one directory up" would
        //     have a shipped app loading resources from alongside itself in
        //     /Applications.
        if code.bundleURL.pathExtension == "xctest" {
            candidates.append(code.bundleURL
                .deletingLastPathComponent()
                .appendingPathComponent(bundleName))
        }
        let stem = (entry.fileName as NSString).deletingPathExtension
        let ext = (entry.fileName as NSString).pathExtension
        for url in candidates.compactMap({ $0 }) {
            guard let bundle = Bundle(url: url) else { continue }
            // `.copy` in Package.swift preserves the directory, so the file
            // lands at `BundledSamples/<file>` inside the resource bundle.
            if let resource = bundle.url(forResource: stem, withExtension: ext,
                                         subdirectory: "BundledSamples") {
                return resource
            }
        }
        return nil
    }
}
